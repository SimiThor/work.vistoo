/**
 * Regenerates every derived artifact of the API contract:
 *   packages/contracts/generated/openapi.json
 *   apps/ios/Packages/VistooKit/Sources/VistooCore/Generated/APIModels.swift
 *   apps/ios/Packages/VistooKit/Sources/VistooCore/Generated/APIEndpoints.swift
 *   apps/ios/Packages/VistooKit/Sources/VistooCore/Generated/DomainConstants.swift
 *
 * Run `npm run generate` after changing packages/domain (dto, validation,
 * constants) or packages/contracts/src. CI fails if the output is stale.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { INVITATION_TTL_DAYS, MEMBER_ROLES, PROJECT_COLORS, ROLE_LABEL, STATUS_LABEL, TASK_STATUSES } from "@vistoo/domain";
import { ALLOWED_FILE_TYPES, CHAT_LIMITS } from "@vistoo/domain/chat-config";
import { UNASSIGNED } from "@vistoo/domain/filters";
import { buildOpenApiDocument } from "../src/openapi";
import { generateSwiftEndpoints, generateSwiftModels } from "./swift";

const root = path.resolve(import.meta.dirname, "../../..");
const swiftDir = path.join(root, "apps/ios/Packages/VistooKit/Sources/VistooCore/Generated");

function write(file: string, content: string) {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content.endsWith("\n") ? content : `${content}\n`);
  console.log(`✓ ${path.relative(root, file)}`);
}

const camel = (s: string) => s.replace(/_([a-z])/g, (_, c: string) => c.toUpperCase());
const str = (s: string) => JSON.stringify(s);

function domainConstants(): string {
  const lines = [
    "// Generated by packages/contracts from packages/domain (npm run generate). Do not edit by hand.",
    "// swiftlint:disable all",
    "import Foundation",
    "",
    "extension TaskStatus {",
    "    /// German label, identical to the web app.",
    "    public var label: String {",
    "        switch self {",
    ...TASK_STATUSES.map((s) => `        case .${camel(s)}: return ${str(STATUS_LABEL[s])}`),
    "        case .unknown(let raw): return raw",
    "        }",
    "    }",
    "}",
    "",
    "extension MemberRole {",
    "    public var label: String {",
    "        switch self {",
    ...MEMBER_ROLES.map((r) => `        case .${camel(r)}: return ${str(ROLE_LABEL[r])}`),
    "        case .unknown(let raw): return raw",
    "        }",
    "    }",
    "}",
    "",
    "/// Muted identification colours of projects (key → label, hex), same palette as the web app.",
    "public struct ProjectColorDefinition: Hashable, Sendable {",
    "    public let key: String",
    "    public let label: String",
    "    public let hex: UInt32",
    "",
    "    public static let all: [ProjectColorDefinition] = [",
    ...Object.entries(PROJECT_COLORS).map(
      ([key, c]) => `        ProjectColorDefinition(key: ${str(key)}, label: ${str(c.label)}, hex: 0x${c.hex.slice(1).toUpperCase()}),`,
    ),
    "    ]",
    "",
    "    /// Unknown keys fall back to grey (as on the web).",
    "    public static func forKey(_ key: String) -> ProjectColorDefinition {",
    "        all.first { $0.key == key } ?? all[0]",
    "    }",
    "}",
    "",
    "/// Offline fallback for limits; the server sends the authoritative values in `Bootstrap.limits`.",
    "public enum DomainDefaults {",
    `    public static let maxMessageLength = ${CHAT_LIMITS.maxMessageLength}`,
    `    public static let messagePageSize = ${CHAT_LIMITS.pageSize}`,
    `    public static let maxFileBytes = ${CHAT_LIMITS.maxFileBytes}`,
    `    public static let maxFilesPerMessage = ${CHAT_LIMITS.maxFilesPerMessage}`,
    `    public static let storageWarnRatio = ${CHAT_LIMITS.warnRatio}`,
    `    public static let invitationTtlDays = ${INVITATION_TTL_DAYS}`,
    "    /// Filter value for \"unassigned\" (shared filter semantics).",
    `    public static let unassigned = ${str(UNASSIGNED)}`,
    "    public static let allowedFileTypes: [Limits.AllowedFileType] = [",
    ...ALLOWED_FILE_TYPES.map(
      (t) =>
        `        Limits.AllowedFileType(label: ${str(t.label)}, extensions: [${t.extensions.map(str).join(", ")}], mimeType: ${str(t.mime)}),`,
    ),
    "    ]",
    "}",
    "",
  ];
  return lines.join("\n");
}

const doc = buildOpenApiDocument();
write(path.join(root, "packages/contracts/generated/openapi.json"), JSON.stringify(doc, null, 2));
// eslint-disable-next-line @typescript-eslint/no-explicit-any
write(path.join(swiftDir, "APIModels.swift"), generateSwiftModels(doc as any));
// eslint-disable-next-line @typescript-eslint/no-explicit-any
write(path.join(swiftDir, "APIEndpoints.swift"), generateSwiftEndpoints(doc as any));
write(path.join(swiftDir, "DomainConstants.swift"), domainConstants());
