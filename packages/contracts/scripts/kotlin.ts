/**
 * OpenAPI (generated/openapi.json) → Kotlin source for the Android app.
 *
 * Counterpart of swift.ts with the same conventions, so both apps read the
 * contract identically:
 *   - response types: `@Serializable data class` (kotlinx.serialization); optional
 *     and nullable fields default to null, unknown keys are ignored by the JSON config,
 *   - request types: plain data classes implementing `ApiRequest` with an explicit
 *     `toJson()`:
 *       required + nullable  → always encoded (explicit JSON null),
 *       optional             → omitted when null,
 *       optional + nullable  → `Patchable<T>` (Unset / Null / Value) for partial updates,
 *   - string enums are OPEN: unknown server values decode to `Unknown(raw)`,
 *   - instants → `java.time.Instant`, calendar days → `CalendarDate`,
 *   - ids stay `String` (lower-case UUIDs exactly as the server sends them),
 *   - maxLength/minLength of request fields → companion constants for client-side checks,
 *   - the same renames as Swift (`Task` → `TaskItem`, `Group` → `ProjectGroup`).
 */

type Schema = {
  $ref?: string;
  type?: string | string[];
  format?: string;
  enum?: string[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: Schema | boolean;
  description?: string;
  maxLength?: number;
  minLength?: number;
};

type Doc = {
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, Schema> };
};

type Operation = {
  operationId: string;
  summary?: string;
  parameters?: { name: string; in: "path" | "query"; required: boolean; schema: Schema }[];
  requestBody?: { content: { "application/json": { schema: Schema } } };
  responses: Record<string, { content?: { "application/json": { schema: Schema } } }>;
  "x-vistoo-auth": string;
  "x-vistoo-retry": string;
};

export const KOTLIN_PACKAGE = "de.vistoo.work.core.generated";

/** Same renames as the Swift generator (readable across both apps). */
const TYPE_NAMES: Record<string, string> = { Task: "TaskItem", Group: "ProjectGroup" };
const RESERVED_NESTED = new Set(["Error", "Type", "Protocol", "Self", "Task", "Group", "Unknown", "Companion", "Serializer"]);
const KEYWORDS = new Set([
  "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
  "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while",
]);

const HEADER = "// Generated by packages/contracts (npm run generate). Do not edit by hand.";

const pascal = (s: string) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const camel = (s: string) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};
const typeName = (component: string) => TYPE_NAMES[component] ?? component;
const refName = (ref: string) => typeName(ref.replace("#/components/schemas/", ""));
const refComponent = (ref: string) => ref.replace("#/components/schemas/", "");
const caseName = (raw: string) => {
  const c = pascal(raw === raw.toUpperCase() ? raw.toLowerCase() : raw);
  return c === "Unknown" ? "UnknownValue" : c;
};
const nestedName = (prop: string) => {
  const n = pascal(prop);
  return RESERVED_NESTED.has(n) ? `${n}Info` : n;
};
const ident = (name: string) => (KEYWORDS.has(name) ? `\`${name}\`` : name);
const str = (s: string) => JSON.stringify(s).replace(/\$/g, "\\$");
const kdoc = (text: string | undefined, pad = "") => (text ? [`${pad}/** ${text.replace(/\*\//g, "*\\/")} */`] : []);
const indent = (text: string, n = 1) =>
  text
    .split("\n")
    .map((l) => (l ? "    ".repeat(n) + l : l))
    .join("\n");

function nullableInner(s: Schema): Schema | null {
  const alts = s.anyOf ?? s.oneOf;
  if (alts && alts.length === 2) {
    const nonNull = alts.find((a) => a.type !== "null");
    if (alts.some((a) => a.type === "null") && nonNull) return nonNull;
  }
  if (Array.isArray(s.type) && s.type.includes("null")) {
    return { ...s, type: s.type.find((t) => t !== "null") };
  }
  return null;
}

/** Resolved Kotlin type plus how to turn a value of it into a JsonElement (requests). */
type KType = { name: string; nullable: boolean; encode: (v: string) => string };

class KotlinEmitter {
  private nested: string[] = [];
  constructor(
    private readonly doc: Doc,
    private readonly mode: "response" | "request",
    private readonly requestComponents: Set<string>,
  ) {}

  /** Inline string enums identical to a component enum reuse that type. */
  private enumComponentFor(values: string[]): string | null {
    for (const [name, s] of Object.entries(this.doc.components.schemas)) {
      if (s.enum && s.enum.length === values.length && s.enum.every((v, i) => v === values[i])) return typeName(name);
    }
    return null;
  }

  ktype(s: Schema, hint: string): KType {
    if (s.$ref) {
      const component = refComponent(s.$ref);
      const name = refName(s.$ref);
      const target = this.doc.components.schemas[component];
      if (target?.enum) return { name, nullable: false, encode: (v) => `JsonPrimitive(${v}.rawValue)` };
      if (this.requestComponents.has(component)) return { name, nullable: false, encode: (v) => `${v}.toJson()` };
      return { name, nullable: false, encode: (v) => `ApiJson.encodeToJsonElement(${name}.serializer(), ${v})` };
    }
    const inner = nullableInner(s);
    if (inner) return { ...this.ktype(inner, hint), nullable: true };
    if (s.enum) {
      const known = this.enumComponentFor(s.enum);
      if (known) return { name: known, nullable: false, encode: (v) => `JsonPrimitive(${v}.rawValue)` };
      const name = nestedName(hint);
      this.nested.push(emitEnum(name, s.enum, s.description));
      return { name, nullable: false, encode: (v) => `JsonPrimitive(${v}.rawValue)` };
    }
    const type = Array.isArray(s.type) ? s.type[0] : s.type;
    const primitive = (name: string): KType => ({ name, nullable: false, encode: (v) => `JsonPrimitive(${v})` });
    switch (type) {
      case "string":
        if (s.format === "date-time") return { name: "Instant", nullable: false, encode: (v) => `JsonPrimitive(Iso8601.format(${v}))` };
        if (s.format === "date") return { name: "CalendarDate", nullable: false, encode: (v) => `JsonPrimitive(${v}.iso)` };
        return primitive("String");
      case "integer":
        return primitive("Long");
      case "number":
        return primitive("Double");
      case "boolean":
        return primitive("Boolean");
      case "array": {
        const item = this.ktype(s.items ?? {}, singular(hint));
        const itemName = item.nullable ? `${item.name}?` : item.name;
        const enc = item.nullable ? (v: string) => `${v}?.let { ${item.encode("it")} } ?: JsonNull` : item.encode;
        return { name: `List<${itemName}>`, nullable: false, encode: (v) => `JsonArray(${v}.map { ${enc("it")} })` };
      }
      case "object": {
        if (s.properties) {
          const name = nestedName(hint);
          this.nested.push(this.emitStruct(name, s));
          return {
            name,
            nullable: false,
            encode: this.mode === "request" ? (v) => `${v}.toJson()` : (v) => `ApiJson.encodeToJsonElement(${name}.serializer(), ${v})`,
          };
        }
        if (s.additionalProperties && typeof s.additionalProperties === "object") {
          const value = this.ktype(s.additionalProperties, hint);
          const valueName = value.nullable ? `${value.name}?` : value.name;
          const enc = value.nullable ? (v: string) => `${v}?.let { ${value.encode("it")} } ?: JsonNull` : value.encode;
          return {
            name: `Map<String, ${valueName}>`,
            nullable: false,
            encode: (v) => `JsonObject(${v}.mapValues { (_, value) -> ${enc("value")} })`,
          };
        }
        return { name: "JsonElement", nullable: false, encode: (v) => v };
      }
      default:
        return { name: "JsonElement", nullable: false, encode: (v) => v };
    }
  }

  emitStruct(name: string, s: Schema): string {
    const saved = this.nested;
    this.nested = [];
    const required = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).map(([key, ps]) => {
      const t = this.ktype(ps, key);
      const isRequired = required.has(key);
      let kind: "plain" | "nullable" | "optional" | "patch" = "plain";
      let decl = t.nullable ? `${t.name}?` : t.name;
      let def = "";
      if (this.mode === "request") {
        if (!isRequired && t.nullable) {
          kind = "patch";
          decl = `Patchable<${t.name}>`;
          def = " = Patchable.Unset";
        } else if (!isRequired) {
          kind = "optional";
          decl = `${t.name}?`;
          def = " = null";
        } else if (t.nullable) {
          kind = "nullable";
        }
      } else if (t.nullable || !isRequired) {
        decl = `${t.name}?`;
        def = " = null";
      }
      const limits = nullableInner(ps) ?? ps;
      const kName = camel(key) === key ? key : camel(key);
      return { key, kName, decl, def, kind, t, ps, limits };
    });

    const lines: string[] = [...kdoc(s.description)];
    if (this.mode === "response") lines.push("@Serializable");
    const params = props.map((p) => {
      const serialName = this.mode === "response" && p.kName !== p.key ? `@SerialName(${str(p.key)}) ` : "";
      return [...kdoc(p.ps.description, "    "), `    ${serialName}val ${ident(p.kName)}: ${p.decl}${p.def},`].join("\n");
    });
    const header =
      props.length === 0
        ? `class ${name}`
        : `data class ${name}(\n${params.join("\n")}\n)`;
    const supertype = this.mode === "request" ? " : ApiRequest" : "";
    const body: string[] = [];
    if (this.mode === "request") {
      const consts: string[] = [];
      for (const p of props) {
        if (typeof p.limits.maxLength === "number") consts.push(`const val ${p.kName}MaxLength = ${p.limits.maxLength}`);
        if (typeof p.limits.minLength === "number" && p.limits.minLength > 0)
          consts.push(`const val ${p.kName}MinLength = ${p.limits.minLength}`);
      }
      if (consts.length) body.push("companion object {", ...consts.map((c) => `    ${c}`), "}", "");
      body.push("override fun toJson(): JsonElement = buildJsonObject {");
      for (const p of props) {
        const v = ident(p.kName);
        if (p.kind === "optional") body.push(`    ${v}?.let { put(${str(p.key)}, ${p.t.encode("it")}) }`);
        else if (p.kind === "patch") body.push(`    ${v}.encodeInto(this, ${str(p.key)}) { ${p.t.encode("it")} }`);
        else if (p.kind === "nullable") body.push(`    put(${str(p.key)}, ${v}?.let { ${p.t.encode("it")} } ?: JsonNull)`);
        else body.push(`    put(${str(p.key)}, ${p.t.encode(v)})`);
      }
      body.push("}");
    }
    if (this.nested.length) {
      if (body.length) body.push("");
      body.push(...this.nested.join("\n\n").split("\n"));
    }
    lines.push(body.length ? `${header}${supertype} {\n${indent(body.join("\n"))}\n}` : `${header}${supertype}`);
    this.nested = saved;
    return lines.join("\n");
  }
}

function singular(hint: string) {
  if (hint.endsWith("ies")) return `${hint.slice(0, -3)}y`;
  if (hint.endsWith("s")) return hint.slice(0, -1);
  return `${hint}Item`;
}

export function emitEnum(name: string, values: string[], description?: string): string {
  const cases = values.map((v) => ({ raw: v, name: caseName(v) }));
  return [
    ...kdoc(description),
    "/** Open enum: values added by a newer server decode to [Unknown]. */",
    `@Serializable(with = ${name}.Serializer::class)`,
    `sealed class ${name}(override val rawValue: String) : OpenEnum {`,
    ...cases.map((c) => `    data object ${c.name} : ${name}(${str(c.raw)})`),
    `    data class Unknown(val raw: String) : ${name}(raw)`,
    "",
    "    final override fun toString(): String = rawValue",
    "",
    "    companion object {",
    `        val knownCases: List<${name}> by lazy { listOf(${cases.map((c) => c.name).join(", ")}) }`,
    "",
    `        fun from(rawValue: String): ${name} = when (rawValue) {`,
    ...cases.map((c) => `            ${str(c.raw)} -> ${c.name}`),
    "            else -> Unknown(rawValue)",
    "        }",
    "    }",
    "",
    `    object Serializer : OpenEnumSerializer<${name}>(${str(name)}, { from(it) })`,
    "}",
  ].join("\n");
}

function requestComponentNames(doc: Doc): Set<string> {
  const out = new Set<string>();
  for (const methods of Object.values(doc.paths)) {
    for (const op of Object.values(methods)) {
      const ref = op.requestBody?.content["application/json"].schema.$ref;
      if (ref) out.add(refComponent(ref));
    }
  }
  return out;
}

const FILE_PREAMBLE = [
  "@file:UseSerializers(InstantSerializer::class)",
  '@file:Suppress("unused", "RedundantVisibilityModifier", "PropertyName", "ktlint")',
  "",
  `package ${KOTLIN_PACKAGE}`,
  "",
  "import de.vistoo.work.core.api.ApiJson",
  "import de.vistoo.work.core.api.ApiRequest",
  "import de.vistoo.work.core.api.InstantSerializer",
  "import de.vistoo.work.core.api.Iso8601",
  "import de.vistoo.work.core.api.OpenEnum",
  "import de.vistoo.work.core.api.OpenEnumSerializer",
  "import de.vistoo.work.core.api.Patchable",
  "import de.vistoo.work.core.api.encodeInto",
  "import de.vistoo.work.core.support.CalendarDate",
  "import java.time.Instant",
  "import kotlinx.serialization.SerialName",
  "import kotlinx.serialization.Serializable",
  "import kotlinx.serialization.UseSerializers",
  "import kotlinx.serialization.json.JsonArray",
  "import kotlinx.serialization.json.JsonElement",
  "import kotlinx.serialization.json.JsonNull",
  "import kotlinx.serialization.json.JsonObject",
  "import kotlinx.serialization.json.JsonPrimitive",
  "import kotlinx.serialization.json.buildJsonObject",
  "",
];

export function generateKotlinModels(doc: Doc): string {
  const requests = requestComponentNames(doc);
  const out: string[] = [HEADER, ...FILE_PREAMBLE];
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    const kName = typeName(name);
    if (schema.enum) {
      out.push(emitEnum(kName, schema.enum, schema.description), "");
      continue;
    }
    const emitter = new KotlinEmitter(doc, requests.has(name) ? "request" : "response", requests);
    if (TYPE_NAMES[name]) out.push(`/** Contract name: \`${name}\` (renamed, as in Swift, to avoid a clash with a common type). */`);
    out.push(emitter.emitStruct(kName, schema), "");
  }
  return out.join("\n");
}

export function generateKotlinEndpoints(doc: Doc): string {
  const requests = requestComponentNames(doc);
  const out: string[] = [
    HEADER,
    '@file:Suppress("unused", "ktlint")',
    "",
    `package ${KOTLIN_PACKAGE}`,
    "",
    "import de.vistoo.work.core.api.AuthLevel",
    "import de.vistoo.work.core.api.Endpoint",
    "import de.vistoo.work.core.api.HttpMethod",
    "import de.vistoo.work.core.api.NoContent",
    "import de.vistoo.work.core.api.RetryPolicy",
    "import de.vistoo.work.core.api.pathSegment",
    "",
    "/** Typed descriptors for every /api/v1 operation. */",
    "object API {",
  ];
  const ops: { op: Operation; method: string; path: string }[] = [];
  for (const [path, methods] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(methods)) ops.push({ op, method, path });
  }
  ops.sort((a, b) => a.op.operationId.localeCompare(b.op.operationId));
  const emitter = new KotlinEmitter(doc, "request", requests);
  for (const { op, method, path } of ops) {
    const params = op.parameters ?? [];
    const args: string[] = [];
    for (const p of params) {
      const t = emitter.ktype(p.schema, p.name);
      args.push(p.required && !t.nullable ? `${ident(p.name)}: ${t.name}` : `${ident(p.name)}: ${t.name}? = null`);
    }
    const bodyRef = op.requestBody?.content["application/json"].schema.$ref;
    if (bodyRef) args.push(`body: ${refName(bodyRef)}`);
    const success = Object.entries(op.responses).find(([code]) => code.startsWith("2"));
    const responseRef = success?.[1].content?.["application/json"].schema.$ref;
    const responseType = responseRef ? refName(responseRef) : "NoContent";
    const kPath = path.replace(/\{(\w+)\}/g, (_, name) => `\${pathSegment(${ident(name)})}`);
    const query = params
      .filter((p) => p.in === "query")
      .map((p) => `${ident(p.name)}?.let { ${str(p.name)} to it.toString() }`);
    out.push("");
    out.push(...kdoc(op.summary, "    "));
    out.push(`    fun ${op.operationId}(${args.join(", ")}): Endpoint<${responseType}> = Endpoint(`);
    out.push(`        method = HttpMethod.${method.toUpperCase()},`);
    out.push(`        path = "${kPath}",`);
    out.push(query.length ? `        query = listOfNotNull(${query.join(", ")}),` : "        query = emptyList(),");
    out.push(`        body = ${bodyRef ? "body.toJson()" : "null"},`);
    out.push(`        auth = AuthLevel.${op["x-vistoo-auth"] === "public" ? "Anonymous" : pascal(op["x-vistoo-auth"])},`);
    out.push(`        retry = RetryPolicy.${pascal(op["x-vistoo-retry"])},`);
    out.push(`        response = ${responseRef ? `${responseType}.serializer()` : "null"},`);
    out.push("    )");
  }
  out.push("}", "");
  return out.join("\n");
}
