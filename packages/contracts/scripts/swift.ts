/**
 * OpenAPI (generated/openapi.json) → Swift source for the iOS app.
 *
 * Deliberately small and dependency-free. Output conventions:
 *   - response types: `Codable, Hashable, Sendable` structs with public memberwise init,
 *   - request types: `Encodable, Sendable` with an explicit encoder:
 *       required + nullable  → always encoded (explicit JSON null),
 *       optional             → omitted when nil,
 *       optional + nullable  → `Patchable<T>` (unset / null / value) for partial updates,
 *   - string enums are OPEN: unknown server values decode to `.unknown(raw)`,
 *   - instants → `Date` (ISO 8601 with fractional seconds), calendar days → `CalendarDate`,
 *   - ids stay `String` (lower-case UUIDs exactly as the server sends them),
 *   - maxLength/minLength of request fields → static constants for client-side checks.
 */

type Schema = {
  $ref?: string;
  type?: string | string[];
  format?: string;
  enum?: string[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: Schema | boolean;
  description?: string;
  maxLength?: number;
  minLength?: number;
  default?: unknown;
};

type Doc = {
  paths: Record<string, Record<string, Operation>>;
  components: { schemas: Record<string, Schema> };
};

type Operation = {
  operationId: string;
  summary?: string;
  parameters?: { name: string; in: "path" | "query"; required: boolean; schema: Schema }[];
  requestBody?: { content: { "application/json": { schema: Schema } } };
  responses: Record<string, { content?: { "application/json": { schema: Schema } } }>;
  "x-vistoo-auth": string;
  "x-vistoo-retry": string;
};

/** Contract names that collide with Swift / SwiftUI types. */
const SWIFT_TYPE_NAMES: Record<string, string> = { Task: "TaskItem", Group: "ProjectGroup" };
const RESERVED_CASES = new Set(["none", "default", "self", "Type", "protocol", "public", "private", "internal"]);
const RESERVED_NESTED = new Set(["Error", "Type", "Protocol", "Self", "Task", "Group"]);

const HEADER = "// Generated by packages/contracts (npm run generate). Do not edit by hand.\n// swiftlint:disable all\n";

const pascal = (s: string) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
const camel = (s: string) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};
const typeName = (component: string) => SWIFT_TYPE_NAMES[component] ?? component;
const refName = (ref: string) => typeName(ref.replace("#/components/schemas/", ""));
const caseName = (raw: string) => {
  const c = camel(raw === raw.toUpperCase() ? raw.toLowerCase() : raw);
  return RESERVED_CASES.has(c) ? `${c}Value` : c;
};
const nestedName = (prop: string) => {
  const n = pascal(prop);
  return RESERVED_NESTED.has(n) ? `${n}Info` : n;
};
const swiftString = (s: string) => JSON.stringify(s);
const indent = (text: string, n = 1) =>
  text
    .split("\n")
    .map((l) => (l ? "    ".repeat(n) + l : l))
    .join("\n");

function nullableInner(s: Schema): Schema | null {
  const alts = s.anyOf ?? s.oneOf;
  if (alts && alts.length === 2) {
    const nonNull = alts.find((a) => a.type !== "null");
    if (alts.some((a) => a.type === "null") && nonNull) return nonNull;
  }
  if (Array.isArray(s.type) && s.type.includes("null")) {
    return { ...s, type: s.type.find((t) => t !== "null") };
  }
  return null;
}

class SwiftEmitter {
  /** Nested type declarations collected while resolving a component. */
  private nested: string[] = [];
  constructor(
    private readonly doc: Doc,
    private readonly mode: "response" | "request",
  ) {}

  /** Inline string enums identical to a component enum reuse that type. */
  private enumComponentFor(values: string[]): string | null {
    for (const [name, s] of Object.entries(this.doc.components.schemas)) {
      if (s.enum && s.enum.length === values.length && s.enum.every((v, i) => v === values[i])) return typeName(name);
    }
    return null;
  }

  swiftType(s: Schema, hint: string): string {
    if (s.$ref) return refName(s.$ref);
    const inner = nullableInner(s);
    if (inner) return `${this.swiftType(inner, hint)}?`;
    if (s.enum) {
      const known = this.enumComponentFor(s.enum);
      if (known) return known;
      const name = nestedName(hint);
      this.nested.push(emitEnum(name, s.enum, s.description));
      return name;
    }
    const type = Array.isArray(s.type) ? s.type[0] : s.type;
    switch (type) {
      case "string":
        if (s.format === "date-time") return "Date";
        if (s.format === "date") return "CalendarDate";
        return "String";
      case "integer":
        return "Int";
      case "number":
        return "Double";
      case "boolean":
        return "Bool";
      case "array":
        return `[${this.swiftType(s.items ?? {}, singular(hint))}]`;
      case "object": {
        if (s.properties) {
          const name = nestedName(hint);
          this.nested.push(this.emitStruct(name, s));
          return name;
        }
        if (s.additionalProperties && typeof s.additionalProperties === "object") {
          return `[String: ${this.swiftType(s.additionalProperties, hint)}]`;
        }
        return "JSONValue";
      }
      default:
        return "JSONValue";
    }
  }

  emitStruct(name: string, s: Schema): string {
    const saved = this.nested;
    this.nested = [];
    const required = new Set(s.required ?? []);
    const props = Object.entries(s.properties ?? {}).map(([key, ps]) => {
      const nullable = nullableInner(ps) !== null;
      const isRequired = required.has(key);
      let type = this.swiftType(ps, key);
      let kind: "plain" | "nullable" | "optional" | "patch" = "plain";
      if (this.mode === "request") {
        if (!isRequired && nullable) {
          kind = "patch";
          type = `Patchable<${type.replace(/\?$/, "")}>`;
        } else if (!isRequired) {
          kind = "optional";
          type = type.endsWith("?") ? type : `${type}?`;
        } else if (nullable) {
          kind = "nullable";
        }
      } else if (!isRequired && !type.endsWith("?")) {
        type = `${type}?`;
      }
      const limits = nullableInner(ps) ?? ps;
      return { key, swiftKey: camel(key) === key ? key : camel(key), type, kind, ps, limits };
    });

    const lines: string[] = [];
    if (s.description) lines.push(`/// ${s.description}`);
    const conformances = this.mode === "request" ? "Encodable, Sendable" : "Codable, Hashable, Sendable";
    lines.push(`public struct ${name}: ${conformances} {`);
    for (const p of props) {
      if (p.ps.description) lines.push(`    /// ${p.ps.description}`);
      lines.push(`    public var ${p.swiftKey}: ${p.type}`);
    }
    if (this.mode === "request") {
      for (const p of props) {
        if (typeof p.limits.maxLength === "number") lines.push(`    public static let ${p.swiftKey}MaxLength = ${p.limits.maxLength}`);
        if (typeof p.limits.minLength === "number" && p.limits.minLength > 0)
          lines.push(`    public static let ${p.swiftKey}MinLength = ${p.limits.minLength}`);
      }
    }
    // Memberwise init (public), optionals default to nil / .unset.
    const params = props.map((p) => {
      const def = p.kind === "patch" ? " = .unset" : p.type.endsWith("?") ? " = nil" : "";
      return `${p.swiftKey}: ${p.type}${def}`;
    });
    lines.push("");
    lines.push(`    public init(${params.join(", ")}) {`);
    for (const p of props) lines.push(`        self.${p.swiftKey} = ${p.swiftKey}`);
    lines.push("    }");
    if (props.some((p) => p.swiftKey !== p.key) || this.mode === "request") {
      lines.push("");
      lines.push("    enum CodingKeys: String, CodingKey {");
      for (const p of props) lines.push(`        case ${p.swiftKey}${p.swiftKey !== p.key ? ` = ${swiftString(p.key)}` : ""}`);
      lines.push("    }");
    }
    if (this.mode === "request") {
      lines.push("");
      lines.push("    public func encode(to encoder: any Encoder) throws {");
      lines.push("        var c = encoder.container(keyedBy: CodingKeys.self)");
      for (const p of props) {
        if (p.kind === "optional") lines.push(`        try c.encodeIfPresent(${p.swiftKey}, forKey: .${p.swiftKey})`);
        else if (p.kind === "patch") lines.push(`        try ${p.swiftKey}.encode(into: &c, forKey: .${p.swiftKey})`);
        else lines.push(`        try c.encode(${p.swiftKey}, forKey: .${p.swiftKey})`);
      }
      lines.push("    }");
    }
    if (this.nested.length) {
      lines.push("");
      lines.push(indent(this.nested.join("\n\n")));
    }
    lines.push("}");
    this.nested = saved;
    return lines.join("\n");
  }
}

function singular(hint: string) {
  if (hint.endsWith("ies")) return `${hint.slice(0, -3)}y`;
  if (hint.endsWith("s")) return hint.slice(0, -1);
  return `${hint}Item`;
}

export function emitEnum(name: string, values: string[], description?: string): string {
  const cases = values.map((v) => ({ raw: v, name: caseName(v) }));
  return [
    description ? `/// ${description}` : null,
    `/// Open enum: values added by a newer server decode to \`.unknown\`.`,
    `public enum ${name}: Codable, Hashable, Sendable {`,
    ...cases.map((c) => `    case ${c.name}`),
    "    case unknown(String)",
    "",
    `    public static let knownCases: [${name}] = [${cases.map((c) => `.${c.name}`).join(", ")}]`,
    "",
    "    public init(rawValue: String) {",
    "        switch rawValue {",
    ...cases.map((c) => `        case ${swiftString(c.raw)}: self = .${c.name}`),
    "        default: self = .unknown(rawValue)",
    "        }",
    "    }",
    "",
    "    public var rawValue: String {",
    "        switch self {",
    ...cases.map((c) => `        case .${c.name}: return ${swiftString(c.raw)}`),
    "        case .unknown(let raw): return raw",
    "        }",
    "    }",
    "",
    "    public init(from decoder: any Decoder) throws {",
    "        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))",
    "    }",
    "",
    "    public func encode(to encoder: any Encoder) throws {",
    "        var c = encoder.singleValueContainer()",
    "        try c.encode(rawValue)",
    "    }",
    "}",
  ]
    .filter((l) => l !== null)
    .join("\n");
}

function isRequestComponent(doc: Doc, name: string): boolean {
  for (const methods of Object.values(doc.paths)) {
    for (const op of Object.values(methods)) {
      const ref = op.requestBody?.content["application/json"].schema.$ref;
      if (ref === `#/components/schemas/${name}`) return true;
    }
  }
  return false;
}

export function generateSwiftModels(doc: Doc): string {
  const out: string[] = [HEADER, "import Foundation", ""];
  for (const [name, schema] of Object.entries(doc.components.schemas)) {
    const swiftName = typeName(name);
    if (schema.enum) {
      out.push(emitEnum(swiftName, schema.enum, schema.description), "");
      continue;
    }
    const emitter = new SwiftEmitter(doc, isRequestComponent(doc, name) ? "request" : "response");
    if (SWIFT_TYPE_NAMES[name]) out.push(`/// Contract name: \`${name}\` (renamed in Swift to avoid a clash with a system type).`);
    out.push(emitter.emitStruct(swiftName, schema), "");
  }
  return out.join("\n");
}

export function generateSwiftEndpoints(doc: Doc): string {
  const out: string[] = [HEADER, "import Foundation", "", "/// Typed descriptors for every /api/v1 operation.", "public enum API {"];
  const ops: { op: Operation; method: string; path: string }[] = [];
  for (const [path, methods] of Object.entries(doc.paths)) {
    for (const [method, op] of Object.entries(methods)) ops.push({ op, method, path });
  }
  ops.sort((a, b) => a.op.operationId.localeCompare(b.op.operationId));
  const emitter = new SwiftEmitter(doc, "request");
  for (const { op, method, path } of ops) {
    const params = op.parameters ?? [];
    const args: string[] = [];
    for (const p of params) {
      const t = emitter.swiftType(p.schema, p.name);
      args.push(`${p.name}: ${p.required ? t : `${t.replace(/\?$/, "")}? = nil`}`);
    }
    const bodyRef = op.requestBody?.content["application/json"].schema.$ref;
    if (bodyRef) args.push(`body: ${refName(bodyRef)}`);
    const success = Object.entries(op.responses).find(([code]) => code.startsWith("2"));
    const responseRef = success?.[1].content?.["application/json"].schema.$ref;
    const responseType = responseRef ? refName(responseRef) : "NoContent";
    const swiftPath = path.replace(/\{(\w+)\}/g, (_, name) => `\\(${name}.pathEncoded)`);
    const query = params
      .filter((p) => p.in === "query")
      .map((p) => `            URLQueryItem.optional(${swiftString(p.name)}, ${p.name})`);
    out.push("");
    if (op.summary) out.push(`    /// ${op.summary}`);
    out.push(`    public static func ${op.operationId}(${args.join(", ")}) -> Endpoint<${responseType}> {`);
    out.push("        Endpoint(");
    out.push(`            method: .${method},`);
    out.push(`            path: "${swiftPath}",`);
    out.push(query.length ? `            query: [\n${query.map((q) => `    ${q}`).join(",\n")}\n            ].compactMap { $0 },` : "            query: [],");
    out.push(`            body: ${bodyRef ? "body" : "nil"},`);
    out.push(`            auth: .${op["x-vistoo-auth"] === "public" ? "anonymous" : camel(op["x-vistoo-auth"])},`);
    out.push(`            retry: .${camel(op["x-vistoo-retry"])}`);
    out.push("        )");
    out.push("    }");
  }
  out.push("}", "");
  return out.join("\n");
}
